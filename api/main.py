"""
Split Step Counter HTTP API.

Endpoints
---------
    GET  /health           liveness check (no auth)
    GET  /v1/features      which features are switched on (for UIs to hide the rest)
    POST /v1/count         multipart upload: field "file" = the video
    POST /v1/upload-url    get a presigned S3 POST so a browser can upload directly
    POST /v1/count/s3      JSON {"bucket": ..., "key": ...}: video already in S3
    POST /v1/report        JSON {"result": <a count response>, "title": ...} -> Markdown report
    GET  /docs             interactive Swagger UI (generated by FastAPI)
    GET  /app/             the Tennis Trainer web page (web/index.html), when present

Both count endpoints take ?model=lstm|rules (default lstm), optional
?drill=auto|forehand|backhand|serve&hand=auto|right|left for stroke training,
and return the dict produced by split_step.analyze.analyze_video().

Features switched off via split_step.features (SPLIT_STEP_FEATURES env var or
features.json) vanish from responses, and requests for them get 404.

Browser flow (public website, see web/index.html):
    1. POST /v1/upload-url {"filename": "match.mp4"}  -> {url, fields, bucket, key}
    2. POST the file to url as multipart form data (fields first, then "file")
    3. POST /v1/count/s3 {"bucket", "key"}            -> count result

Configuration (environment variables)
-------------------------------------
    ALLOWED_ORIGINS  comma-separated origins allowed by CORS, e.g.
                     "https://www.example.com,http://localhost:5500". Unset = no CORS.
    UPLOAD_BUCKET    bucket for browser uploads. Enables /v1/upload-url and LOCKS
                     /v1/count/s3 to keys this API issued (UPLOAD_PREFIX/<random>),
                     so a public caller can't make the service read other objects.
    API_KEY          if set, every /v1 request must send header  X-API-Key: <value>.
                     For server-to-server use only — a key in browser JS is public.
    MAX_UPLOAD_MB    size limit for uploads, direct or presigned (default 200)
    MAX_VIDEO_SECONDS  longest video analysed (default 600 = 10 min; 413 beyond)
    RATE_LIMIT_PER_HOUR  analyses per client IP per hour (default 0 = unlimited)
    SPLIT_STEP_MODELS_DIR   where the model files live (default <repo>/models)

Run locally:   uvicorn api.main:app --reload
On Lambda:     api/lambda_handler.handler wraps this app with Mangum.
"""

import os
import re
import secrets
import tempfile
import uuid
from typing import Literal

from fastapi import Depends, FastAPI, File, Header, HTTPException, Query, UploadFile
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import PlainTextResponse
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel

from split_step import features
from split_step.analyze import VideoError, VideoTooLong, analyze_video
from split_step.report import to_markdown

from api.limits import rate_limit

ModelName = Literal["lstm", "rules"]
DrillName = Literal["auto", "forehand", "backhand", "serve"]
HandName  = Literal["auto", "right", "left"]

MAX_UPLOAD_BYTES = int(float(os.environ.get("MAX_UPLOAD_MB", "200")) * 1024 * 1024)
# Longest video analysed; keeps one request well inside Lambda's 15 min limit
MAX_VIDEO_SECONDS = float(os.environ.get("MAX_VIDEO_SECONDS", "600"))
UPLOAD_PREFIX    = "uploads/"
UPLOAD_URL_TTL_S = 600
_CHUNK = 1024 * 1024
_VIDEO_EXTS = {".mp4", ".mov", ".m4v", ".webm", ".avi", ".mkv"}
_ISSUED_KEY = re.compile(rf"^{re.escape(UPLOAD_PREFIX)}[0-9a-f]{{32}}\.[a-z0-9]{{2,4}}$")

app = FastAPI(
    title="Split Step Counter API",
    version="1.3.0",
    description="Tennis video analysis: split-step counting (MediaPipe pose + LSTM or rules) "
                "and forehand / backhand / serve training feedback.",
)

_origins = [o.strip() for o in os.environ.get("ALLOWED_ORIGINS", "").split(",") if o.strip()]
if _origins:
    app.add_middleware(
        CORSMiddleware,
        allow_origins=_origins,
        allow_methods=["GET", "POST"],
        allow_headers=["Content-Type", "X-API-Key"],
    )


# Serve the web UI from the API itself, so it works with no separate website
# (and no CORS) — e.g. straight from the Lambda Function URL.
_WEB_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "web")
if os.path.isdir(_WEB_DIR):
    app.mount("/app", StaticFiles(directory=_WEB_DIR, html=True), name="web")


def require_api_key(x_api_key: str | None = Header(default=None)) -> None:
    """Enforce X-API-Key when the API_KEY env var is set; no-op otherwise."""
    expected = os.environ.get("API_KEY")
    if expected and not (x_api_key and secrets.compare_digest(x_api_key, expected)):
        raise HTTPException(status_code=401, detail="Missing or invalid X-API-Key header.")


def require_feature(name: str):
    """Dependency: 404 when a feature is switched off (it should look absent)."""
    def check() -> None:
        if not features.enabled(name):
            raise HTTPException(status_code=404, detail=f"Feature '{name}' is disabled.")
    return check


class AnalysisOptions:
    """Query parameters shared by both count endpoints, checked against the feature switches."""

    def __init__(
        self,
        model: ModelName = Query("lstm", description="Split-step model"),
        require_full_pose: bool = Query(True, description="Skip the LSTM on frames where the hips, "
                                                          "ankles, heels and toes aren't all visible"),
        drill: DrillName | None = Query(None, description="Stroke training: analyse swings as this "
                                                          "stroke ('auto' classifies each swing)"),
        hand: HandName = Query("auto", description="Hitting hand for stroke training"),
        include_pose: bool = Query(False, description="Also return the per-frame skeleton "
                                                      "(for drawing overlays; ~7 KB per second, max ~1 MB)"),
    ):
        flags = features.all_features()
        counting = flags["split_step_counting"]
        if counting and not flags[features.model_feature(model)]:
            raise HTTPException(status_code=404, detail=f"Model '{model}' is disabled.")
        if drill is not None and not flags[features.drill_feature(drill)]:
            raise HTTPException(status_code=404,
                                detail=f"Feature '{features.drill_feature(drill)}' is disabled.")
        if include_pose and not flags["pose_overlay"]:
            raise HTTPException(status_code=404, detail="Feature 'pose_overlay' is disabled.")
        if not counting and drill is None:
            raise HTTPException(status_code=400, detail="Split-step counting is disabled; choose a drill.")
        self.kwargs = dict(model=model, require_full_pose=require_full_pose, drill=drill, hand=hand,
                           count_split_steps=counting, split_step_metrics=flags["split_step_metrics"],
                           split_step_timing=flags["split_step_timing"],
                           rally_stats=flags["rally_stats"], include_pose=include_pose,
                           ready_position=flags["ready_position"],
                           camera_view_check=flags["camera_view_check"],
                           footwork=flags["footwork"], fatigue=flags["fatigue_trend"],
                           highlights=flags["swing_highlights"], practice=flags["practice_plan"],
                           coach=flags["coach_summary"])


class CountResult(BaseModel):
    count: int | None = None
    model: str | None = None
    events: list[dict] | None = None
    session: dict | None = None
    frames_tracked: int | None = None
    strokes: dict | None = None
    timing: dict | None = None
    rallies: dict | None = None
    pose: dict | None = None
    recovery: dict | None = None
    camera: dict | None = None
    footwork: dict | None = None
    fatigue: dict | None = None
    highlights: dict | None = None
    coach: dict | None = None
    frames: int
    frames_analysed: int | None = None
    frames_with_pose: int
    duration_ms: float
    fps: float
    processing_s: float


class ReportRequest(BaseModel):
    result: dict
    title: str = "Tennis session report"


class S3Video(BaseModel):
    bucket: str
    key: str


class UploadRequest(BaseModel):
    filename: str = "video.mp4"


class UploadTicket(BaseModel):
    url: str
    fields: dict[str, str]
    bucket: str
    key: str
    max_bytes: int
    expires_in: int


def _suffix(name: str | None) -> str:
    ext = os.path.splitext(name or "")[1].lower()
    return ext if ext in _VIDEO_EXTS else ".mp4"


def _upload_bucket() -> str | None:
    return os.environ.get("UPLOAD_BUCKET") or None


def _s3_client():
    import boto3  # lazy: only the S3 endpoints need it
    from botocore.config import Config

    region = os.environ.get("AWS_REGION") or os.environ.get("AWS_DEFAULT_REGION") or "us-east-1"
    # Regional, virtual-hosted URLs: the global endpoint answers presigned
    # requests for non-us-east-1 buckets with a redirect that browsers block.
    return boto3.client(
        "s3", region_name=region,
        endpoint_url=f"https://s3.{region}.amazonaws.com",
        config=Config(signature_version="s3v4", s3={"addressing_style": "virtual"}),
    )


def _analyze_file(path: str, opts: AnalysisOptions) -> dict:
    try:
        return analyze_video(path, **opts.kwargs, max_seconds=MAX_VIDEO_SECONDS or None)
    except VideoTooLong as e:
        raise HTTPException(status_code=413, detail=str(e))
    except VideoError as e:
        raise HTTPException(status_code=422, detail=str(e))


@app.get("/health")
def health() -> dict:
    return {"status": "ok"}


@app.get("/v1/features")
def list_features() -> dict:
    """Feature switches, so a UI can hide what's turned off. Public on purpose."""
    return {"features": features.all_features(),
            "descriptions": {f["name"]: f["description"] for f in features.describe()}}


# Endpoints are plain `def` (not async) so FastAPI runs the CPU-heavy analysis
# in its threadpool instead of blocking the event loop.
_COUNT_ROUTE = dict(response_model=CountResult, response_model_exclude_none=True)


@app.post("/v1/count", **_COUNT_ROUTE,
          dependencies=[Depends(require_api_key), Depends(require_feature("direct_upload")),
                        Depends(rate_limit)])
def count_upload(
    file: UploadFile = File(..., description="Video file (mp4, mov, webm, ...)"),
    opts: AnalysisOptions = Depends(),
) -> dict:
    fd, path = tempfile.mkstemp(suffix=_suffix(file.filename))
    try:
        written = 0
        with os.fdopen(fd, "wb") as out:
            while chunk := file.file.read(_CHUNK):
                written += len(chunk)
                if written > MAX_UPLOAD_BYTES:
                    raise HTTPException(status_code=413,
                                        detail=f"Upload exceeds {MAX_UPLOAD_BYTES // (1024 * 1024)} MB.")
                out.write(chunk)
        if written == 0:
            raise HTTPException(status_code=400, detail="Uploaded file is empty.")
        return _analyze_file(path, opts)
    finally:
        os.remove(path)


@app.post("/v1/report", response_class=PlainTextResponse,
          dependencies=[Depends(require_api_key), Depends(require_feature("markdown_report"))])
def markdown_report(req: ReportRequest) -> PlainTextResponse:
    """Turn a count response into a readable Markdown report (no video needed,
    nothing stored). Same output as `analyze --report`."""
    try:
        text = to_markdown(req.result, req.title.strip()[:120] or "Tennis session report")
    except (KeyError, TypeError, ValueError, AttributeError, IndexError):
        raise HTTPException(status_code=422, detail="result must be a response from /v1/count.")
    return PlainTextResponse(text, media_type="text/markdown; charset=utf-8")


@app.post("/v1/upload-url", response_model=UploadTicket,
          dependencies=[Depends(require_api_key), Depends(require_feature("browser_uploads"))])
def upload_url(req: UploadRequest) -> dict:
    """Issue a short-lived presigned S3 POST for one video under UPLOAD_PREFIX.
    S3 itself enforces the size limit, so oversized uploads never reach us."""
    bucket = _upload_bucket()
    if not bucket:
        raise HTTPException(status_code=501, detail="Browser uploads are not configured (UPLOAD_BUCKET unset).")
    key = f"{UPLOAD_PREFIX}{uuid.uuid4().hex}{_suffix(req.filename)}"
    post = _s3_client().generate_presigned_post(
        Bucket=bucket, Key=key,
        Conditions=[["content-length-range", 1, MAX_UPLOAD_BYTES]],
        ExpiresIn=UPLOAD_URL_TTL_S,
    )
    return {"url": post["url"], "fields": post["fields"], "bucket": bucket, "key": key,
            "max_bytes": MAX_UPLOAD_BYTES, "expires_in": UPLOAD_URL_TTL_S}


@app.post("/v1/count/s3", **_COUNT_ROUTE,
          dependencies=[Depends(require_api_key), Depends(require_feature("browser_uploads")),
                        Depends(rate_limit)])
def count_s3(video: S3Video, opts: AnalysisOptions = Depends()) -> dict:
    """Analyse a video stored in S3. Preferred on Lambda/API Gateway, whose
    request bodies are capped at a few MB. The service's IAM role needs
    s3:GetObject on the object. When UPLOAD_BUCKET is set, only keys issued by
    /v1/upload-url are accepted."""
    from botocore.exceptions import BotoCoreError, ClientError

    bucket = _upload_bucket()
    if bucket and (video.bucket != bucket or not _ISSUED_KEY.match(video.key)):
        raise HTTPException(status_code=403, detail="Only videos uploaded via /v1/upload-url can be counted.")

    fd, path = tempfile.mkstemp(suffix=_suffix(video.key))
    os.close(fd)
    try:
        try:
            _s3_client().download_file(video.bucket, video.key, path)
        except ClientError as e:
            code = e.response.get("Error", {}).get("Code", "")
            status = 404 if code in ("404", "NoSuchKey", "NoSuchBucket") else 403 if code in ("403", "AccessDenied") else 502
            raise HTTPException(status_code=status, detail=f"S3 error: {code or e}")
        except BotoCoreError as e:
            raise HTTPException(status_code=502, detail=f"S3 error: {e}")
        return _analyze_file(path, opts)
    finally:
        if os.path.exists(path):
            os.remove(path)
